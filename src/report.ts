import type { Assessment, Checklist, ValidationOutcome } from "./types.js";

export function renderReport(
  checklist: Checklist,
  assessment: Assessment,
  outcome: ValidationOutcome,
): string {
  const lines: string[] = [
    `# Production AI readiness: ${escapeText(assessment.feature.name)}`,
    "",
    `**Decision:** ${outcome.ready ? "READY" : "NOT READY"} for **${assessment.feature.maturity}**`,
    "",
    `Owner: ${escapeText(assessment.feature.owner)}  `,
    `Assessment date: ${assessment.assessedAt}  `,
    `Checklist: ${escapeText(checklist.name)} ${checklist.version}`,
    "",
    escapeText(assessment.feature.description),
    "",
    "## Summary",
    "",
    "| Applicable | Pass | Not applicable | Partial | Fail | Missing |",
    "| ---: | ---: | ---: | ---: | ---: | ---: |",
    `| ${outcome.summary.applicable} | ${outcome.summary.passed} | ${outcome.summary.notApplicable} | ${outcome.summary.partial} | ${outcome.summary.failed} | ${outcome.summary.missing} |`,
    "",
  ];

  if (outcome.errors.length > 0) {
    lines.push("## Release blockers", "");
    for (const error of outcome.errors) {
      lines.push(`- ${escapeText(error)}`);
    }
    lines.push("");
  }

  if (outcome.warnings.length > 0) {
    lines.push("## Warnings", "");
    for (const warning of outcome.warnings) {
      lines.push(`- ${escapeText(warning)}`);
    }
    lines.push("");
  }

  lines.push(
    "## Controls",
    "",
    "| Control | Category | Level | Required | Status | Owner | Review | Evidence |",
    "| --- | --- | --- | :---: | --- | --- | --- | --- |",
  );

  const byId = new Map(assessment.controls.map((result) => [result.id, result]));
  const levels = { prototype: 0, pilot: 1, production: 2 };
  const selectedLevel = levels[assessment.feature.maturity];
  for (const control of checklist.controls) {
    if (levels[control.level] > selectedLevel) {
      continue;
    }
    const result = byId.get(control.id);
    const evidence =
      result?.evidence.map((item) => `[${escapeText(item.label)}](${escapeUri(item.uri)})`).join(", ") ??
      "—";
    lines.push(
      `| ${escapeCell(control.title)} \`${control.id}\` | ${control.category} | ${control.level} | ${control.required ? "yes" : "no"} | ${result?.status ?? "**missing**"} | ${escapeCell(result?.owner ?? "—")} | ${result?.reviewDate ?? "—"} | ${evidence || "—"} |`,
    );
  }

  lines.push("", "## Rationale", "");
  for (const control of checklist.controls) {
    const result = byId.get(control.id);
    if (result === undefined || levels[control.level] > selectedLevel) {
      continue;
    }
    lines.push(
      `### ${escapeText(control.title)}`,
      "",
      `${escapeText(result.rationale)}`,
      "",
      `Guidance: ${escapeText(control.guidance)}`,
      "",
    );
  }

  lines.push(
    "---",
    "",
    "Generated by [Production AI Checklist](https://github.com/attractorhq/production-ai-checklist).",
    "",
  );
  return lines.join("\n");
}

function escapeText(value: string): string {
  return value.replaceAll("<", "&lt;").replaceAll(">", "&gt;");
}

function escapeCell(value: string): string {
  return escapeText(value).replaceAll("|", "\\|").replaceAll("\n", " ");
}

function escapeUri(value: string): string {
  return value.replaceAll(" ", "%20").replaceAll(")", "%29");
}
